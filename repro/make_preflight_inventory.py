"""List historical preflight inputs omitted from the public source checkout."""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path


def sha(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def classify(name: str):
    path = Path(name)
    base = path.name
    stage = path.parts[1] if len(path.parts) > 1 else ""
    if "wdc_format_hourly" in path.parts:
        url = ("https://wdcapi.bgs.ac.uk/data/zipped-data/hour/COI?years=2007-2017&file_format=wdc&orientation=XYZF"
               if "2007-2017" in base else
               "https://wdcapi.bgs.ac.uk/data/zipped-data/hour/COI?start_dt=2007-01-01&end_dt=2018-01-01&file_format=wdc&orientation=XYZF")
        return "provider_raw", "WDC Edinburgh/BGS historical HTTP response; see S7C acquisition records", url, "Provider terms; historical bytes required for strict gate"
    if base == "S7C_wdc_crosscheck.csv":
        return "provider_derived_large", "python phase2a/S7C/d2c.py after authenticated WDC tabular source and D2b comparison", "", "WDC-derived; do not bundle without rights review"
    if base == "D2b_meanfield_comparison.csv":
        return "provider_derived", "python phase2a/S7B/d2b_meanfield.py after WDC/Mendeley inputs and approved amendment", "", "Mendeley/WDC-derived; do not bundle without rights review"
    if base in ("G4R_pca_cache.npz", "G4R_sq_cache.npz"):
        return "derived_cache", "python phase2a/G4R/g4r_run.py after authenticated G2R inputs", "", "Derived; verify exact historical SHA"
    if base.endswith("_review.zip"):
        return "historical_review_bundle", f"Archived {stage} review ZIP from author audit snapshot; {stage} finalize/report script documents creation", "", "Inspect members and rights before redistribution"
    if base.endswith(".docx") or "protocol" in base.lower() or base in ("S7B_decisions_approved.md", "G0-registration-3_D2c.md"):
        return "author_protocol", "Exact author-approved protocol/amendment from preserved audit snapshot", "", "Obtain from authors; do not infer chronology from hash"
    if base in ("mendeley_bundle.js", "mendeley_landing.html"):
        return "acquisition_web_snapshot", "Historical Mendeley landing/API page saved during G0 acquisition", "https://data.mendeley.com/datasets/jcmdrm5f5x/1", "New fetch cannot reconstruct historical bytes"
    if base == "input_manifest.csv":
        return "acquisition_manifest", "G0 inventory generated by phase2a/G0/g0_inventory.py; historical copy is authoritative", "", "Contains local paths and provider references; redact before sharing"
    if base == "G0_validation.json":
        return "audit_metadata", "G0 inventory generated by phase2a/G0/g0_inventory.py; historical copy is authoritative", "", "May contain local paths; redact before sharing"
    if base == "python_environment.json":
        return "environment_metadata", "G0 inventory generated by phase2a/G0/g0_inventory.py", "", "May contain local interpreter path"
    if base.endswith(".log") or base.endswith(".jsonl"):
        return "historical_execution_record", f"Exact {stage} run/acquisition log from preserved author audit snapshot", "", "Historical timestamps cannot be regenerated"
    if base.endswith(".md"):
        return "historical_audit_document", f"Exact {stage} approved decision/change/report from preserved author audit snapshot", "", "Author review before sharing"
    if base.endswith(".json"):
        return "historical_audit_metadata", f"Exact {stage} acquisition/preparation/preflight JSON from preserved author audit snapshot", "", "May contain local paths"
    raise RuntimeError(f"Unclassified input: {name}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-root", type=Path, required=True)
    parser.add_argument("--repo-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    source, repo = args.source_root.resolve(), args.repo_root.resolve()
    expected = json.loads((repo / "phase3/F3A_preflight.json").read_text(encoding="utf-8"))["frozen_sha256"]
    rows = []
    for rel, digest in sorted(expected.items()):
        if (repo / rel).is_file():
            continue
        path = source / rel
        if not path.is_file():
            raise FileNotFoundError(path)
        actual = sha(path)
        if actual != digest:
            raise RuntimeError(f"Historical preflight SHA mismatch: {rel}: {actual} != {digest}")
        kind, route, url, release_note = classify(rel)
        rows.append({"relative_path": rel, "sha256": digest, "size_bytes": path.stat().st_size,
                     "category": kind, "access_or_build": route, "provider_url": url,
                     "sharing_note": release_note, "required_by_strict_preflight": "True",
                     "direct_phase3_numerical_input": "False"})
    if len(rows) != 46:
        raise RuntimeError(f"Expected 46 omitted frozen inputs, found {len(rows)}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=rows[0].keys(), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    print(json.dumps({"rows": len(rows), "categories": {kind: sum(r["category"] == kind for r in rows)
                                                           for kind in sorted({r["category"] for r in rows})},
                      "manifest_sha256": sha(args.output)}, indent=2))


if __name__ == "__main__":
    main()
